const assert=require('node:assert/strict');
const {C,act,flags}=require('./modern-support.cjs');
const {boot}=require('./workshop-ui.cjs');
let s=act(C.enableWeekly(C.fresh(3,{...flags,traction:true})),'start');
s=C.tick(s,60);
s=act(act(s,'readWeek'),'weekend',{choice:'rest'});
s.weekly.obligations.push({id:'office',category:'office',startDay:7,amount:50000});
s.weekly.obligations.push({id:'employee',category:'salary',startDay:9,amount:500});
s=C.tick(s,60);
const r=s.weekly.reports.at(-1);
assert.equal(r.expenses.office,30000);
assert.equal(r.expenses.salary,100);
assert.equal(r.result,-30100);
assert.equal(r.cashEnd,-5100);
assert.equal(r.cashDifference,0);
assert(r.entries.every(e=>e.week===2&&e.day===10&&e.status==='posted'));
assert.equal(new Set(r.entries.map(e=>e.id)).size,r.entries.length);
const loaded=C.load(JSON.stringify(s));
assert.deepEqual(C.tick(loaded,60).weekly.reports, s.weekly.reports);
const a=boot(new Map([['the-founder-contract-v1',JSON.stringify(s)]]),'0.42');
const html=a.el('weekly-modal').innerHTML;
assert(html.includes('sem base comparável'));
assert(html.includes('Caixa negativo'));
assert(html.includes('Aluguel'));
assert(html.includes('Equipe'));
assert(!html.includes('Diferença na conciliação'));
console.log('PASS: competência, caixa negativo, comparação com base zero e relatório persistido.');
