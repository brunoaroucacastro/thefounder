const assert=require('node:assert/strict');
const {C,act,until,launch}=require('./modern-support.cjs');
let state=launch({price:125});
state.traction=C.Reach.defaultMix();
state.marketing.mix=[...state.traction];
state.learningWindow.traction=true;
state=until(state,'recap');
assert(C.Learning.status(state,'campaign').ready);
assert(state.stock>0);
const extended=act(state,'extendSales');
assert(Math.abs(extended.sales.windowEnd-extended.sales.windowStart-420)<1e-8);
assert.equal(extended.stock,state.stock);
assert.equal(extended.cash,state.cash);
assert.equal(extended.rolls.length,state.rolls.length);
assert.throws(()=>act(extended,'extendSales'));
const manufacturing=act(act(state,'restockSize',{quantity:10}),'crew',{task:'produce',quantity:10});
assert.equal(manufacturing.crew.quantity,10);
assert.equal(manufacturing.generation,state.generation);
const a=require('./workshop-ui.cjs').boot(new Map(),'0.46');
a.click('start');
a.click('product',{id:'headphones'});
a.until('customer');
a.click('customer',{id:a.state().personaCandidates[0]});
a.click('reveal');
const tray=a.el('tray'),nodes=new Map();
tray.querySelector=selector=>{if(!nodes.has(selector))nodes.set(selector,{style:{}});return nodes.get(selector);};
const target={dataset:{mixIndex:'0'},value:'100'};
tray.listeners.input({target});
tray.listeners.change({target});
assert.deepEqual(Array.from(a.state().tractionWeights),[100,20,15,15,15,15]);
assert.equal(a.state().traction.reduce((x,y)=>x+y,0),100);
console.log('PASS: extensão, produção sem versão nova, lição de marketing e prioridades independentes.');
