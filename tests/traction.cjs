const assert=require('node:assert/strict');
const {C,act,until,flags}=require('./modern-support.cjs');
let s=act(C.fresh(3,{...flags,traction:true}),'start');
s=until(act(s,'product',{id:'headphones'}),'customer');
s=act(s,'customer',{id:s.personaCandidates[0]});
s=act(s,'attribute',{id:'quality',delta:1});
s=act(s,'reveal');
assert.equal(s.phase,'promotion');
assert.equal(s.placeId,'online');
assert.throws(()=>act(s,'marketingMix',{mix:[20,20,20,20,20,20]}));
const mix=[30,20,15,10,15,10];
s=act(s,'marketingMix',{mix});
assert.deepEqual(C.load(JSON.stringify(s)).traction,mix);
assert.notEqual(C.Reach.marketing(s,mix),C.Reach.marketing(s,[100,0,0,0,0,0]));
assert.notEqual(C.Reach.marketing(s,mix),C.Reach.marketing({...s,productId:'mouse'},mix));
s=act(s,'confirmPromotion');
const cash=s.cash;
s=until(act(s,'build'),'testReady');
assert.equal(s.cash,cash-8000);
assert.equal(C.cac(s),0);
s=act(s,'test',{},13);
s=until(act(s,'testChoice',{choice:s.quality===0?'repair':'continue'}),'batchPlanning');
s=act(act(s,'confirmBatch'),'confirmPrice');
const plan=C.Reach.plan(s);
s=act(s,'launchAndRoll');
assert.deepEqual(s.marketing.mix,mix);
assert.equal(s.marketing.actualLeads,plan.total);
assert.equal(s.marketing.actualLeads,Math.round(s.marketing.baseLeads*s.marketing.marketingMultiplier));
assert.throws(()=>act(s,'launchAndRoll'));
s=until(act(s,'ackLaunch'),'selling');
s=until(s,'recap');
assert.equal(s.campaignCost,0);
assert.equal(s.campaignFixedCost,0);
assert.deepEqual(C.load(JSON.stringify(s)).history.at(-1).marketing.mix,mix);
s=act(s,'newCampaign');
s=act(s,'marketingMix',{mix:[0,0,0,0,0,100]});
const before=s.cash;
s=until(act(s,'recampaignStart'),'recampaignReady');
assert.equal(s.cash,before);
s=act(s,'rollRecampaign');
assert.deepEqual(s.recampaign.roll.mix,[0,0,0,0,0,100]);
assert.deepEqual(C.load(JSON.stringify(s)).traction,[0,0,0,0,0,100]);
console.log('PASS: fluxo e-commerce, mix persistido, lançamento único e recampanha sem cobrança.');

