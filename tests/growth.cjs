const assert=require('node:assert/strict');
const {C,act,until,launch}=require('./modern-support.cjs');
const make=()=>C.Reach.enableGrowth({...launch({price:125}),traction:C.Reach.defaultMix()});
let s=make();
const initial=C.Reach.plan(s);
assert(initial.total>=500&&initial.total<=800);
const other=C.G.personas(s).find(p=>p.id!==s.clientId).id;
const segment=C.Reach.growthProfile(s);
C.Reach.commit(s,{promo:s.promo});
assert(C.Reach.growthProfile(s).segment.available<segment.capacity);
assert.equal(C.Reach.growthProfile({...s,clientId:other}).segment.available,segment.capacity);
assert.equal(C.Reach.growthProfile({...s,productId:'speaker'}),null);
const depleted=C.Reach.growthProfile(s).segment;
depleted.available=0;
depleted.used=depleted.allowance;
assert.equal(C.Reach.plan(s).total,0);
for(let n=0;n<36;n++)C.Reach.renewGrowth(s);
assert(Math.abs(depleted.available/segment.capacity-.5)<.001);
s=until(make(),'recap');
s=act(s,'newCampaign');
s=act(s,'campaignPersona',{id:other});
assert.throws(()=>act(s,'campaignKind',{kind:'retarget'}));
s=act(s,'recampaignStart');
assert.equal(s.clientId,other);
assert.equal(s.recampaign.kind,'reach');
s=until(s,'recampaignReady');
s=act(act(s,'rollRecampaign'),'recampaignContinue');
assert(s.market.active.growthKey.endsWith(':'+other));
s=until(s,'recap');
assert(s.market.growth.audience>0);
assert.deepEqual(C.load(JSON.stringify(s)).market.growth,s.market.growth);
console.log('PASS: alcance inicial, segmentos, renovação, troca de público e save.');
// Start from an established company with a funded inventory, and run real sales and accounting.
let scale=make();
scale=act(scale,'stopSales');
scale.productId='keyboard';
scale.clientId='calls';
scale.level=10;
scale.quality=3;
scale.attributes=Object.fromEntries(C.axes(scale).map(a=>[a.id,0]));
const persona=C.G.personas(scale).find(p=>p.id===scale.clientId);
for(const [axis] of Object.entries(persona.weights).sort((a,b)=>b[1]-a[1]).slice(0,3))scale.attributes[axis]=5;
scale.price=200;
scale.cash=5000000;
scale.stock=12000;
scale.inventoryBook=scale.stock*C.unitCost(scale);
scale.market.growth.audience=10000;
scale.market.growth.reputation=88;
for(let i=0;i<5;i++)scale.market.growth.validated['test-'+i]=true;
scale=C.enableWeekly(scale);
scale=act(scale,'extendSales');
const planned=scale.marketing.actualLeads;
scale=C.tick(scale,240);
const week=scale.weekly.reports.at(-1);
assert(week.revenue>=1000000);
assert.equal(week.cashDifference,0);
assert(scale.stock>=0);
console.log({planned,sold:scale.sold,revenue:week.revenue,costs:week.costs});
